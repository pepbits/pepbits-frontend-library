#!/usr/bin/env node
// Generates src/modules/registration/front-desk/styles.css: the Tailwind 4 utilities used by the
// front desk pages copied from the AllyVora clinical workspace, compiled with the source's theme
// (app/globals.css `@theme inline`) and scoped to `.allyvora-front-desk`, so the copied markup keeps
// its classes without adding the source theme to the healthcare app's global Tailwind build.
// Usage (from demo-apps/healthcare): node scripts/allyvora-front-desk-styles.mjs
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, join} from 'node:path';
import {fileURLToPath} from 'node:url';
import postcss from 'postcss';
import tailwind from '@tailwindcss/postcss';

const here = dirname(fileURLToPath(import.meta.url));
const folder = join(here, '../src/modules/registration/front-desk');
const out = join(folder, 'styles.css');
const SCOPE = '.allyvora-front-desk';

// The source theme names, mapped onto the library's theme tokens so the pages follow the
// effective theme preference (light and dark palettes) instead of fixed source colours.
const TOKENS = {
  canvas: 'var(--bg)', surface: 'var(--surface)', raised: 'var(--surface-2)', sunken: 'var(--surface-3)',
  line: 'var(--border)', 'line-strong': 'var(--border-strong)',
  ink: 'var(--text)', 'ink-2': 'var(--text-muted)', 'ink-3': 'var(--text-subtle)',
  lapis: 'var(--primary-fill, var(--primary))', 'lapis-hover': 'var(--primary-strong)', 'lapis-soft': 'var(--primary-soft)', 'lapis-ink': 'var(--primary-strong)',
  ok: 'var(--success-ink, var(--success))', 'ok-soft': 'color-mix(in srgb, var(--success) 12%, var(--surface))',
  warn: 'var(--warning-ink, var(--warning))', 'warn-fill': 'var(--warning)', 'warn-soft': 'color-mix(in srgb, var(--warning) 14%, var(--surface))',
  crit: 'var(--danger-fill, var(--danger))', 'crit-soft': 'color-mix(in srgb, var(--danger) 10%, var(--surface))',
  ai: '#5a35c8', 'ai-soft': 'color-mix(in srgb, #5a35c8 12%, var(--surface))',
};

const input = `
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/utilities.css" layer(utilities) source(none);
@source "${folder}/*.tsx";
@custom-variant dark (&:where([data-allyvora-front-desk-dark], [data-allyvora-front-desk-dark] *));
@theme inline {
  --font-display: var(--font-ui);
  --font-sans: var(--font-ui);
${Object.keys(TOKENS).map(name => `  --color-${name}: var(--c-${name});`).join('\n')}
  --radius-ctl: 9px;
  --radius-panel: var(--radius, 14px);
}
`;

const result = await postcss([tailwind({base: folder, optimize: {minify: false}})]).process(input, {from: join(folder, 'tailwind-input.css')});
const root = postcss.parse(result.css);
// Unwrap cascade layers: the scoped rules must win over the host's layered utilities inside the scope.
root.walkAtRules('layer', rule => {if (rule.nodes) rule.replaceWith(rule.nodes); else rule.remove();});
root.walkRules(rule => {
  if (rule.parent?.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  for (let parent = rule.parent; parent; parent = parent.parent) if (parent.type === 'rule') return; // nested: already scoped by its parent
  rule.selectors = rule.selectors.map(selector => {
    if (selector === ':root' || selector === ':host') return SCOPE;
    return `${SCOPE} ${selector}`;
  });
  rule.selectors = [...new Set(rule.selectors)];
});

const base = `${SCOPE} {
${Object.entries(TOKENS).map(([name, value]) => `  --c-${name}: ${value};`).join('\n')}
  color: var(--c-ink);
  font-size: 14px;
  line-height: 1.5;
  padding: 16px 20px 24px;
}
${SCOPE} :is(h1, h2, h3, h4) { font-family: var(--font-ui); color: var(--c-ink); letter-spacing: -0.012em; margin: 0; }
${SCOPE} :is(p, dl, dd, ol, ul, fieldset) { margin: 0; }
${SCOPE} .num { font-variant-numeric: tabular-nums; font-feature-settings: "tnum"; }
${SCOPE} input[type="number"] { -moz-appearance: textfield; appearance: textfield; }
`;
writeFileSync(out, `/* Generated by scripts/allyvora-front-desk-styles.mjs from the AllyVora clinical workspace theme. Do not edit. */\n${base}\n${root.toString().trimEnd()}\n`);
console.log(`Wrote ${out} (${readFileSync(out, 'utf8').length} bytes)`);
